create table public.anganwadi_centers (
  id bigint generated by default as identity not null,
  state_name text not null,
  district_name text not null,
  project_name text not null,
  sector_name text not null default ''::text,
  gp text not null default ''::text,
  area text not null default ''::text,
  awc_name text not null,
  "createdAt" timestamp with time zone null default now(),
  "updatedAt" timestamp with time zone null default now(),
  constraint anganwadi_centers_pkey primary key (id)
) TABLESPACE pg_default;

create unique index if not exists anganwadi_centers_unique
  on public.anganwadi_centers (
    state_name,
    district_name,
    project_name,
    sector_name,
    gp,
    area,
    awc_name
  );

create index IF not exists idx_anganwadi_centers_district on public.anganwadi_centers using btree (district_name) TABLESPACE pg_default;

create index IF not exists idx_anganwadi_centers_state on public.anganwadi_centers using btree (state_name) TABLESPACE pg_default;


create table public.anganwadi_districts (
  id bigint generated by default as identity not null,
  state text not null,
  district_id text not null,
  district_name text not null,
  source_url text not null,
  login_url text not null,
  captcha_url text not null,
  submit_url text not null,
  step_1_url text not null,
  mobile text null,
  password text null,
  start_date date null,
  end_date date null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint anganwadi_districts_pkey primary key (id)
) TABLESPACE pg_default;

create unique index if not exists anganwadi_districts_unique
  on public.anganwadi_districts (state, district_id, source_url);

create table public.anganwadi_vacancies (
  id bigint generated by default as identity not null,
  center_id bigint not null,
  post_code text not null,
  post_name text not null,
  vacancy_count integer not null default 0,
  status text not null default 'open'::text,
  start_date date null,
  end_date date null,
  "createdAt" timestamp with time zone null default now(),
  "updatedAt" timestamp with time zone null default now(),
  constraint anganwadi_vacancies_pkey primary key (id),
  constraint fk_anganwadi_vacancies_center_id foreign KEY (center_id) references anganwadi_centers (id) on delete CASCADE
) TABLESPACE pg_default;

create unique index if not exists anganwadi_vacancies_unique
  on public.anganwadi_vacancies (center_id, post_code, post_name);

create index IF not exists idx_anganwadi_vacancies_center_id on public.anganwadi_vacancies using btree (center_id) TABLESPACE pg_default;

DO $$
DECLARE
  target_table text;
  identity_generation text;
  max_id bigint;
  sequence_name text;
BEGIN
  FOREACH target_table IN ARRAY ARRAY[
    'anganwadi_centers',
    'anganwadi_vacancies'
  ] LOOP
    SELECT columns.is_identity
    INTO identity_generation
    FROM information_schema.columns
    WHERE columns.table_schema = 'public'
      AND columns.table_name = target_table
      AND columns.column_name = 'id';

    IF identity_generation IS DISTINCT FROM 'YES' THEN
      sequence_name := target_table || '_id_seq';

      EXECUTE format(
        'CREATE SEQUENCE IF NOT EXISTS public.%I',
        sequence_name
      );

      EXECUTE format(
        'SELECT COALESCE(MAX(id), 0) FROM public.%I',
        target_table
      ) INTO max_id;

      PERFORM setval(
        format('public.%I', sequence_name)::regclass,
        max_id + 1,
        false
      );

      EXECUTE format(
        'ALTER TABLE public.%I ALTER COLUMN id SET DEFAULT nextval(%L)',
        target_table,
        format('public.%I', sequence_name)
      );

      EXECUTE format(
        'ALTER SEQUENCE public.%I OWNED BY public.%I.id',
        sequence_name,
        target_table
      );
    END IF;
  END LOOP;
END $$;